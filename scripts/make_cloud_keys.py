"""
scripts/make_cloud_keys.py - Write cloud_keys.py with the MinIO keys before a build.

The keys come from the MINIO_ACCESS_KEY / MINIO_SECRET_KEY environment variables (GitHub
Actions secrets) or else from `accesskey=` / `secretkey=` lines in .env. Without keys the
build still works; cloud backup then says it is not available. The keys are never printed.

    python scripts/make_cloud_keys.py [--env .env] [--out cloud_keys.py]
"""

import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def read_env_file(path: Path) -> dict[str, str]:
    values = {}
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                name, value = line.split("=", 1)
                values[name.strip().lower()] = value.strip().strip('"').strip("'")
    return values


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--env", default=str(ROOT / ".env"))
    parser.add_argument("--out", default=str(ROOT / "cloud_keys.py"))
    args = parser.parse_args()

    file_values = read_env_file(Path(args.env))
    access = os.environ.get("MINIO_ACCESS_KEY") or file_values.get("accesskey", "")
    secret = os.environ.get("MINIO_SECRET_KEY") or file_values.get("secretkey", "")
    out = Path(args.out)
    if not (access and secret):
        out.unlink(missing_ok=True)          # never ship keys left over from an older build
        print("No MinIO keys found - cloud backup will be unavailable")
        return
    out.write_text('"""MinIO keys for cloud backup. Generated by scripts/make_cloud_keys.py - '
                   'never commit."""\n\n'
                   f"ACCESS_KEY = {json.dumps(access)}\nSECRET_KEY = {json.dumps(secret)}\n",
                   encoding="utf-8")
    print(f"{out.name} written")


if __name__ == "__main__":
    main()
